// Expose global translation applicator
function applyLanguage(lang) {
  if (!geraldTranslations[lang]) lang = 'en';
  localStorage.setItem('gerald_lang', lang);
  
  // Update elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (geraldTranslations[lang][key]) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = geraldTranslations[lang][key];
      } else {
        el.innerHTML = geraldTranslations[lang][key];
      }
    }
  });

  // Update language switcher indicator if present
  const langDisplay = document.getElementById('current-lang-display');
  if (langDisplay) {
    const labels = { en: 'EN (English)', tn: 'TN (Setswana)', fr: 'FR (Français)', de: 'DE (Deutsch)' };
    langDisplay.textContent = labels[lang] || 'EN (English)';
  }
}

// Auto-apply on load
if (typeof window !== 'undefined') {
  window.addEventListener('DOMContentLoaded', () => {
    const savedLang = localStorage.getItem('gerald_lang') || 'en';
    applyLanguage(savedLang);
  });
}
